export type SearchTimeKey = keyof (typeof messages)["en-CA"];

/** Translations for the metadata search bar and Fix time dialog. */
export function useSearchTimeI18n() {
  const { locale } = useI18n();
  return useCallback(
    (key: SearchTimeKey, params?: Record<string, string | number>) => {
      const template = messages[locale][key] ?? messages["en-CA"][key];
      return template.replace(/\{(\w+)\}/g, (match, token: string) =>
        params?.[token] === undefined ? match : String(params[token]),
      );
    },
    [locale],
  );
}
